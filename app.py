# ============================================================
# DATA LOADERS
# ============================================================

@st.cache_data
def load_label_column():
    """Load only the Label column from the cleaned dataset."""

    if not DATA_PATH.exists():
        return None

    try:
        return pd.read_parquet(
            DATA_PATH,
            columns=["Label"]
        )
    except Exception:
        return None


@st.cache_data
def load_pipeline_summary():
    """Load pipeline summary if generated by the backend."""

    if not SUMMARY_PATH.exists():
        return {}

    try:
        with open(SUMMARY_PATH, "r", encoding="utf-8") as f:
            return json.load(f)
    except Exception:
        return {}


@st.cache_data
def load_attack_events():
    """Load attack event output."""

    if not EVENTS_PATH.exists():
        return None

    try:
        return pd.read_csv(EVENTS_PATH)
    except Exception:
        return None


@st.cache_data
def count_csv_rows(path):
    """Count CSV rows without loading the entire file."""

    if not path.exists():
        return None

    try:
        with open(path, "rb") as f:
            return max(0, sum(1 for _ in f) - 1)
    except Exception:
        return None


